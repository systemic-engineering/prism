//! State equivalence is not trajectory equivalence.
//!
//! Wojciech Kaleta's crowbar (2026-09-28): show the smallest system in which
//! the distinction survives control conditions. The null model to beat is
//! ordinary causal computation with non-commuting updates and path dependence.
//!
//! The trajectory instrument is a trace in Foata normal form under an
//! independence relation (Mazurkiewicz; `docs/math/nonlinear-inference.md` section 2,
//! T1 and T4). Two words are the same trajectory iff one becomes the other by
//! swapping adjacent independent steps.
//!
//! The independence relation is declared from read/write footprints, never
//! derived from the outcome. Otherwise "traces agree when states agree" would
//! hold by construction (Mara, T7 circularity).

use std::collections::BTreeSet;

use prismqueer::oid::{Addressable, Oid};
use prismqueer::time::{Independence, Monophony, Polyphony, Progression, Touches};

/// A step that touches named sites.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord)]
struct Step {
    name: &'static str,
    reads: BTreeSet<Oid>,
    writes: BTreeSet<Oid>,
}

fn site(name: &str) -> Oid {
    Oid::hash(name.as_bytes())
}

fn step(name: &'static str, reads: &[&str], writes: &[&str]) -> Step {
    Step {
        name,
        reads: reads.iter().map(|s| site(s)).collect(),
        writes: writes.iter().map(|s| site(s)).collect(),
    }
}

impl Addressable for Step {
    fn oid(&self) -> Oid {
        let reads: Vec<&str> = self.reads.iter().map(Oid::as_str).collect();
        let writes: Vec<&str> = self.writes.iter().map(Oid::as_str).collect();
        Oid::hash(format!("{}|r:{}|w:{}", self.name, reads.join(","), writes.join(",")).as_bytes())
    }
}

impl Touches for Step {
    fn reads(&self) -> &BTreeSet<Oid> {
        &self.reads
    }
    fn writes(&self) -> &BTreeSet<Oid> {
        &self.writes
    }
}

fn same(a: &Oid, b: &Oid) -> bool {
    a.as_str() == b.as_str()
}

// --- Preconditions on the instrument (T1 confound) ---

#[test]
fn footprint_independence_is_symmetric_and_irreflexive() {
    let steps = [
        step("a", &[], &["x"]),
        step("b", &[], &["y"]),
        step("c", &["x"], &["z"]),
        step("d", &["y"], &["y"]),
    ];
    let i = Polyphony;
    for p in &steps {
        assert!(!i.independent(p, p), "{} is independent of itself", p.name);
        for q in &steps {
            assert_eq!(
                i.independent(p, q),
                i.independent(q, p),
                "asymmetric on ({}, {})",
                p.name,
                q.name
            );
        }
    }
}

// --- T1: the congruence is generated by independent swaps ---

#[test]
fn swapping_independent_steps_is_the_same_trajectory() {
    let u = step("u", &[], &["x", "y"]);
    let a = step("a", &["x"], &["x"]);
    let b = step("b", &["y"], &["y"]);
    let v = step("v", &["x", "y"], &[]);
    assert!(
        Polyphony.independent(&a, &b),
        "precondition: a and b touch disjoint sites"
    );

    let ab: Progression<Step, Polyphony> =
        Progression::from_word([u.clone(), a.clone(), b.clone(), v.clone()]);
    let ba: Progression<Step, Polyphony> = Progression::from_word([u, b, a, v]);

    assert!(ab == ba, "independent swap changed the trace");
    assert!(
        same(&ab.oid(), &ba.oid()),
        "independent swap changed the address"
    );
    assert_eq!(ab.len(), Some(4), "sequential time counts every step");
    assert_eq!(
        ab.height(),
        Some(3),
        "parallel time: u, then a and b together, then v"
    );
}

#[test]
fn swapping_dependent_steps_is_a_different_trajectory() {
    let a = step("a", &[], &["x"]);
    let b = step("b", &["x"], &["y"]);
    assert!(
        !Polyphony.independent(&a, &b),
        "precondition: b reads what a writes"
    );

    let ab: Progression<Step, Polyphony> = Progression::from_word([a.clone(), b.clone()]);
    let ba: Progression<Step, Polyphony> = Progression::from_word([b, a]);

    assert!(ab != ba, "dependent swap left the trace unchanged");
    assert!(
        !same(&ab.oid(), &ba.oid()),
        "dependent swap left the address unchanged"
    );
}

// --- T4: the relation and the step boundaries are part of the address ---

#[test]
fn the_same_word_under_linear_time_is_a_different_trajectory() {
    let a = step("a", &[], &["x"]);
    let b = step("b", &[], &["y"]);

    let nonlinear: Progression<Step, Polyphony> = Progression::from_word([a.clone(), b.clone()]);
    let linear: Progression<Step, Monophony> = Progression::from_word([a, b]);

    assert_eq!(
        nonlinear.height(),
        Some(1),
        "independent steps share one Foata step"
    );
    assert_eq!(
        linear.height(),
        Some(2),
        "under Monophony every step is its own"
    );
    assert!(
        !same(&nonlinear.oid(), &linear.oid()),
        "{{a,b}} and {{a}}{{b}} must not share an address"
    );
}

// --- Wojciech's control: same visible state, different trajectory ---

/// Two heat flows under non-commuting Laplacians, applied in both orders to a
/// constant section. Constants are harmonic for every graph, so the visible
/// state is identical either way. The flows do not commute on states in
/// general (the commutator is non-zero), so declaring them dependent is sound,
/// and the trace keeps the order the state forgot.
///
/// This is the state half of the crowbar only. The future half (same visible
/// state, different reachable futures) needs a step that consults the record;
/// `settle` does not, so it is the Markov control.
#[cfg(feature = "lapack")]
#[test]
fn state_equivalence_is_not_trajectory_equivalence() {
    use prismqueer::spectral::settle::{settle, Noise, Pitches, Time};
    use prismqueer::spectral::Dissonance;
    use prismqueer::spectral::{graph_from_edges, Graph};
    use terni::Imperfect;

    let a = graph_from_edges(&[(0, 1), (1, 2)]);
    let b = graph_from_edges(&[(1, 0), (0, 2)]);
    match Dissonance::of(&a, &b) {
        Imperfect::Success(cs) => assert!(!cs.spectrum.is_empty(), "precondition: [L_a, L_b] != 0"),
        other => panic!("precondition: commutator must be measured cleanly, got {other:?}"),
    }

    let s = Pitches::new([(0, 1.0), (1, 1.0), (2, 1.0)]);
    let run = |first: &Graph, second: &Graph| -> Pitches {
        let mid = settle(first, &s, Time(0.5), Noise(1e-9))
            .ok()
            .expect("first flow");
        settle(second, &mid, Time(0.5), Noise(1e-9))
            .ok()
            .expect("second flow")
    };
    let ab = run(&a, &b);
    let ba = run(&b, &a);
    for v in 0..3 {
        assert!(
            (ab.get(v).unwrap() - ba.get(v).unwrap()).abs() < 1e-12,
            "visible state differs at vertex {v}"
        );
    }

    let flow_a = step("settle under a", &["section"], &["section"]);
    let flow_b = step("settle under b", &["section"], &["section"]);
    let t_ab: Progression<Step, Polyphony> =
        Progression::from_word([flow_a.clone(), flow_b.clone()]);
    let t_ba: Progression<Step, Polyphony> = Progression::from_word([flow_b, flow_a]);
    assert!(
        !same(&t_ab.oid(), &t_ba.oid()),
        "the trace forgot the order too"
    );
}
